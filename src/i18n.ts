export function locale(settings: ShelfSettings): Locale {
  return settings.language === 'auto'
    ? getLanguage().startsWith('ja')
      ? 'ja'
      : 'en'
    : settings.language;
}
export function text(settings: ShelfSettings, key: TextKey): string {
  return (locale(settings) === 'ja' ? ja : en)[key];
}
