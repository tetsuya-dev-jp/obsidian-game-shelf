export function localizedText(
  locale: 'en' | 'ja',
  key: TextKey,
  values: Record<string, string | number> = {},
): string {
  return (locale === 'ja' ? ja : en)[key].replace(/\{\{[^{}]*\}\}|\{([a-zA-Z][a-zA-Z0-9_]*)\}/g, (match, name: string | undefined) =>
    name && Object.hasOwn(values, name) ? String(values[name]) : match,
  );
}

export class LocalizedError extends Error {
  constructor(
    readonly key: TextKey,
    readonly values: Record<string, string | number> = {},
  ) {
    super(localizedText('en', key, values));
    this.name = 'LocalizedError';
  }
}

export function resolveLocale(language: 'auto' | 'en' | 'ja', obsidianLanguage: string): 'en' | 'ja' {
  return language === 'auto' ? (obsidianLanguage.startsWith('ja') ? 'ja' : 'en') : language;
}
